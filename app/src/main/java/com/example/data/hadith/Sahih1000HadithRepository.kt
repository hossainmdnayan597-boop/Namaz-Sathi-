    fun searchHadiths(query: String, categoryId: String = "all", page: Int = 1, pageSize: Int = 50): List<HadithItem> {
        val q = query.trim().lowercase()
        val baseList = if (categoryId == "all") ALL_1000_HADITHS else ALL_1000_HADITHS.filter { it.categoryId == categoryId }

        if (q.isBlank()) {
            return baseList
        }

        // Search by exact number (e.g., "75", "100")
        val numMatch = q.toIntOrNull()
        if (numMatch != null && numMatch in 1..1000) {
            val single = ALL_1000_HADITHS.find { it.id == "hadith_$numMatch" }
            if (single != null) {
                return listOf(single)
            }
        }

        return baseList.filter {
            it.titleBangla.contains(q) ||
            it.hadithNumber.contains(q) ||
            it.bookSourceBangla.contains(q) ||
            it.narratorBangla.contains(q) ||
            it.translationBangla.contains(q) ||
            it.lessonsBangla.contains(q) ||
            it.arabicText.contains(q)
        }
    }
